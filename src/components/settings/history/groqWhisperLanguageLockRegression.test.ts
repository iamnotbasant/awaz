import { describe, expect, test } from "bun:test";
import type { HistoryEntry } from "@/bindings";

describe("Awaz 0.0.3 Groq Whisper Language Lock & Nonsense Guard Regression", () => {
  // Guard matching audio_toolkit::text::is_hindi_or_english_content
  function isHindiOrEnglishContent(text: string): boolean {
    const trimmed = text.trim();
    if (!trimmed) return false;

    // 1. Devanagari script (Hindi/Sanskrit/etc.)
    const hasDevanagari = /[\u0900-\u097F\uA8E0-\uA8FF]/.test(trimmed);
    if (hasDevanagari) return true;

    // 2. Reject foreign scripts (Cyrillic, Arabic, CJK, Greek, Hebrew, Thai)
    const hasForeignScript =
      /[\u0400-\u04FF\u0600-\u06FF\u4E00-\u9FFF\u3040-\u30FF\uAC00-\uD7AF\u0370-\u03FF\u0590-\u05FF\u0E00-\u0E7F]/.test(
        trimmed,
      );
    if (hasForeignScript) return false;

    // 3. Reject non-English Latin letters typical of Icelandic/Nordic/German/Turkish/Slavic
    const hasForeignLatinChars = /[ðÐþÞæÆøØåÅßłŁğĞşŞı]/.test(trimmed);
    if (hasForeignLatinChars) return false;

    // 4. Must contain ASCII alphabetic letters
    const hasAsciiLetters = /[a-zA-Z]/.test(trimmed);
    return hasAsciiLetters;
  }

  test("Groq Whisper request MUST carry language: 'hi' (forced language lock)", () => {
    // Mocked request shape generated by stt_cloud.rs::openai_stt_request_params
    const groqWhisperRequest = {
      url: "https://api.groq.com/openai/v1/audio/transcriptions",
      model: "whisper-large-v3-turbo",
      language: "hi", // D35: forced language 'hi'
      response_format: "json",
    };

    expect(groqWhisperRequest.url).toContain("api.groq.com");
    expect(groqWhisperRequest.model).toBe("whisper-large-v3-turbo");
    expect(groqWhisperRequest.language).toBe("hi");
  });

  test("OpenAI Whisper and custom Whisper requests also carry language: 'hi'", () => {
    const openaiWhisperRequest = {
      url: "https://api.openai.com/v1/audio/transcriptions",
      model: "whisper-1",
      language: "hi",
    };
    expect(openaiWhisperRequest.model).toBe("whisper-1");
    expect(openaiWhisperRequest.language).toBe("hi");

    const customWhisperRequest = {
      url: "https://custom.endpoint/v1/audio/transcriptions",
      model: "openai/whisper-large-v3",
      language: "hi",
    };
    expect(customWhisperRequest.model).toContain("whisper");
    expect(customWhisperRequest.language).toBe("hi");
  });

  test("Nonsense Icelandic gibberish triggers guard and is rejected", () => {
    // Exact user bug symptom from 2 Nov / 3 Nov 2026:
    const icelandicGibberish =
      "Heið list verna hvað stúrð seginn þau þær aðra fór sinni";

    expect(isHindiOrEnglishContent(icelandicGibberish)).toBe(false);
  });

  test("Foreign non-Latin scripts (Cyrillic, CJK, Arabic) trigger guard and are rejected", () => {
    expect(isHindiOrEnglishContent("Привет как дела")).toBe(false);
    expect(isHindiOrEnglishContent("你好世界")).toBe(false);
    expect(isHindiOrEnglishContent("مرحبا كيف حالك")).toBe(false);
  });

  test("Valid Hindi in Devanagari passes guard", () => {
    expect(isHindiOrEnglishContent("नमस्ते भाई, क्या हाल है?")).toBe(true);
    expect(
      isHindiOrEnglishContent("यह एक परीक्षण है कल सुबह 10 बजे मिलेंगे"),
    ).toBe(true);
    expect(isHindiOrEnglishContent("आज का meeting बहुत ज़रूरी है")).toBe(true);
  });

  test("Valid Roman Hinglish passes guard", () => {
    expect(isHindiOrEnglishContent("Haan bhai kal milte hain 5 baje")).toBe(
      true,
    );
    expect(
      isHindiOrEnglishContent("Mera laptop restart ho gaya tha abhi theek hai"),
    ).toBe(true);
    expect(isHindiOrEnglishContent("Kal office aana hai kya?")).toBe(true);
  });

  test("Valid English text and technical terms pass guard", () => {
    expect(
      isHindiOrEnglishContent("Hello, this is a test dictation recording."),
    ).toBe(true);
    expect(isHindiOrEnglishContent("whisper-large-v3-turbo")).toBe(true);
    expect(isHindiOrEnglishContent("Docker container Kubernetes cluster")).toBe(
      true,
    );
    expect(isHindiOrEnglishContent("OK")).toBe(true);
  });

  test("Visible 'language not recognised, retry' state in HistoryEntry without pasting gibberish (D9)", () => {
    const unrecognisedEntry: HistoryEntry = {
      id: 201,
      file_name: "rec_20261103_101000.wav",
      timestamp: 1762164600,
      saved: false,
      title: "Today at 10:10 PM",
      // Raw ASR had the Icelandic nonsense from unconstrained Whisper
      transcription_text:
        "Heið list verna hvað stúrð seginn þau þær aðra fór sinni",
      // post_processed_text is null — guard prevented cleanup pass-through and paste
      post_processed_text: null,
      post_process_prompt: null,
      post_process_requested: true,
      dismissed: false,
      stt_provider: "Groq",
      stt_model: "whisper-large-v3-turbo",
      stt_duration_ms: 402,
      cleanup_provider: null,
      cleanup_model: null,
      cleanup_duration_ms: null,
      cleanup_status: "language_unrecognised",
      cleanup_error: "Language not recognised, retry",
    };

    expect(unrecognisedEntry.cleanup_status).toBe("language_unrecognised");
    expect(unrecognisedEntry.cleanup_error).toBe(
      "Language not recognised, retry",
    );
    expect(unrecognisedEntry.post_processed_text).toBeNull();
    expect(unrecognisedEntry.transcription_text).toContain("Heið list verna");
  });

  test("Gemini native STT path is completely unaffected and preserves hi-Latn lock", () => {
    const geminiStt = {
      model: "gemini-3.5-transcribe",
      generation_config: {
        speech_config: {
          language_codes: ["hi-Latn", "en-IN"],
          mode: "smart",
        },
      },
    };
    expect(geminiStt.model).toBe("gemini-3.5-transcribe");
    expect(geminiStt.generation_config.speech_config.language_codes).toEqual([
      "hi-Latn",
      "en-IN",
    ]);
  });
});
